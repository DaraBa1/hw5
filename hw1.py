print("=== Рівень 1 ===")
a = 17
b = 5

print("Сума:", a + b)
print("Різниця:", a - b)
print("Добуток:", a * b)
print("Частка (/):", a / b)

print("Цілочисельне ділення (//):", a // b)
print("Залишок від ділення (%):", a % b)
# Пояснення: // виконує цілочисельне ділення (відкидає залишок / округлює вниз),
# а / виконує звичайне ділення з плаваючою точкою (float).

print("2 у 10-му степені:", 2 ** 10)
print("10 у 3-му степені:", 10 ** 3)

price = 249.99
count = 3
total_cost = price * count
print("Загальна вартість покупки:", total_cost)

print("Типи результатів:")
print("type(7 / 2):", type(7 / 2))       # float (звичайне ділення завжди дає float)
print("type(7 // 2):", type(7 // 2))     # int (ділення двох цілих чисел дає int)
print("type(7.0 // 2):", type(7.0 // 2)) # float (якщо хоча б один операнд float)
# Чому типи різні? Python зберігає інформацію про тип операндів: наявність числа з плаваючою точкою (float) автоматично робить результат float.

name = "Python"
print("Назва тричі:", name * 3)

greeting = "Привіт, " + "світ!"
print("Склеєний рядок:", greeting)


