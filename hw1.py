n = 473
print(f"Остання цифра числа 473: {n % 10}")

# Сотні, десятки й одиниці для n = 473
hundreds = n // 100
tens = (n // 10) % 10
units = n % 10
print(f"Число 473: сотні = {hundreds}, десятки = {tens}, одиниці = {units}")

# Сума цифр тризначного числа n = 859
n_num = 859
sum_digits = (n_num // 100) + ((n_num // 10) % 10) + (n_num % 10)
print(f"Сума цифр числа 859: {sum_digits}")

# Перевернути тризначне число (з 123 отримати 321)
orig = 123
reversed_num = (orig % 10) * 100 + ((orig // 10) % 10) * 10 + (orig // 100)
print(f"Перевернуте число з 123: {reversed_num}")

# Квадратний корінь з 144 через ** 0.5
